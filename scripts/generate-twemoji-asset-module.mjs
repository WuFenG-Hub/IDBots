#!/usr/bin/env node
/**
 * Generate the embedded Twemoji asset module (packager-decoupled artwork).
 *
 * Incident this mechanizes away (desktop 1.0.9 asar): the old manifest used
 * `new URL('./assets/twemoji/<stem>.svg', import.meta.url)`, so artwork
 * delivery depended on the bundler emitting 85 separate .svg files that every
 * later packaging/copy step (asar, tenant-image dir copies, deploy filters)
 * had to carry correctly. When they don't, <img> load fails and Chromium
 * renders the alt codepoint — the "dev fine, packaged fallback" bug.
 *
 * This script (idempotent, rerunnable):
 *   1. Rewrites src/renderer/components/chat/twemoji.ts manifest values from
 *      `new URL(...)` expressions to `TWEMOJI_DATA_URLS['<stem>']` lookups
 *      (char→stem pairing stays human-visible in the manifest; regex-based,
 *      so reruns after the rewrite are a no-op).
 *   2. Emits src/renderer/components/chat/twemojiAssets.generated.ts with the
 *      FULL `data:image/svg+xml,<encodeURIComponent(svg)>` string per stem —
 *      complete literals (not runtime concatenation), so built chunks carry
 *      ≥85 findable `data:image/svg+xml` references and the bundle is
 *      self-contained: no vite asset emission, no sibling asset files.
 *
 * Source of truth: src/renderer/components/chat/assets/twemoji/*.svg
 * (kept on disk as generation input only; never emitted at runtime).
 * Run: pnpm generate:twemoji-assets
 * Gate: scripts/check-mobile-twemoji-bundle.mjs fails if `new URL(` returns.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const MANIFEST = path.join(REPO_ROOT, 'src/renderer/components/chat/twemoji.ts');
const ASSETS_DIR = path.join(REPO_ROOT, 'src/renderer/components/chat/assets/twemoji');
const GENERATED = path.join(REPO_ROOT, 'src/renderer/components/chat/twemojiAssets.generated.ts');

// --- parse manifest (char → stem) -------------------------------------------

const source = readFileSync(MANIFEST, 'utf8');
const pairRe = /^\s*"((?:[^"\\]|\\.)+)"\s*:\s*(?:new URL\('\.\/assets\/twemoji\/([0-9a-f]+)\.svg', import\.meta\.url\)\.href|TWEMOJI_DATA_URLS\['([0-9a-f]+)'\])/gm;
const pairs = [];
let m;
while ((m = pairRe.exec(source)) !== null) {
  pairs.push({ key: JSON.parse(`"${m[1]}"`), stem: m[2] ?? m[3] });
}
if (pairs.length !== 85) {
  console.error(`[generate-twemoji-asset-module] expected 85 manifest pairs, parsed ${pairs.length}`);
  process.exit(1);
}
const stems = pairs.map(({ stem }) => stem);
if (new Set(stems).size !== 85) {
  console.error('[generate-twemoji-asset-module] manifest stems are not unique');
  process.exit(1);
}

// --- rewrite twemoji.ts values (no-op after first run) -----------------------

const rewritten = source.replace(
  /new URL\('\.\/assets\/twemoji\/([0-9a-f]+)\.svg', import\.meta\.url\)\.href/g,
  (_, stem) => `TWEMOJI_DATA_URLS['${stem}']`,
);
let manifestOut = rewritten;
if (rewritten !== source && !/^import \{ TWEMOJI_DATA_URLS \} from '\.\/twemojiAssets\.generated';$/m.test(manifestOut)) {
  manifestOut = `import { TWEMOJI_DATA_URLS } from './twemojiAssets.generated';\n\n${manifestOut}`;
}
if (manifestOut !== source) {
  writeFileSync(MANIFEST, manifestOut);
  console.log('[generate-twemoji-asset-module] rewrote twemoji.ts manifest values to TWEMOJI_DATA_URLS lookups');
} else {
  console.log('[generate-twemoji-asset-module] twemoji.ts already uses embedded data URIs (no-op)');
}

// --- emit generated module ----------------------------------------------------

const entries = pairs.map(({ stem }) => {
  const svg = readFileSync(path.join(ASSETS_DIR, `${stem}.svg`), 'utf8');
  return `  '${stem}': 'data:image/svg+xml,${encodeURIComponent(svg)}',`;
});

const header = `// Generated by scripts/generate-twemoji-asset-module.mjs — DO NOT EDIT BY HAND.
// Source of truth: src/renderer/components/chat/assets/twemoji/*.svg
// Regenerate: pnpm generate:twemoji-assets
//
// Artwork: Twemoji 14.0.2 (CC-BY 4.0) — LICENSES/twemoji-NOTICE.md
//
// Each value is the COMPLETE \`data:image/svg+xml,<encodeURIComponent(svgText)>\`
// literal for one vendored SVG, embedded as a plain string so bundles stay
// self-contained: no vite asset emission and no packager-visible asset files
// (the asset-delivery failure mode behind the desktop 1.0.9 asar incident).

export const TWEMOJI_DATA_URLS: Readonly<Record<string, string>> = {
${entries.join('\n')}
};
`;

writeFileSync(GENERATED, header);
console.log(`[generate-twemoji-asset-module] wrote ${GENERATED} (${pairs.length} embedded data URIs)`);
